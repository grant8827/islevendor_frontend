import { useCallback, useEffect, useState } from 'react';
import { Copy } from 'lucide-react';
import { apiRequest } from '../../../api/client.js';
import { useToast } from '../../../context/ToastContext.jsx';
import { Badge, ListState } from '../adminShared.jsx';
import { SectionTitle } from './payShared.jsx';

const STATUS = {
  ok: ['OK', 'bg-primary/10 text-primary-dark border-primary/30'],
  warning: ['Check', 'bg-amber-100 text-amber-700 border-amber-300'],
  error: ['Problem', 'bg-red-100 text-red-700 border-red-300'],
  missing: ['Not set', 'bg-slate-100 text-slate-600 border-slate-300'],
};

// Every address payments depend on, checked against the rules: HTTPS, WiPay
// addresses on WiPay's own domain and matching the environment, our return
// and webhook addresses on this API. Set in the deployment, not here.
export default function GatewayLinks() {
  const { notify } = useToast();
  const [links, setLinks] = useState(null);
  const [error, setError] = useState(null);
  const load = useCallback(() => {
    apiRequest('/admin/pay/links')
      .then(setLinks)
      .catch((err) => setError(err.message));
  }, []);
  useEffect(load, [load]);

  return (
    <div className="max-w-5xl">
      <SectionTitle
        title="Gateway links"
        description="Addresses come from the deployment's environment, so they can't be changed from a dashboard. Webhook addresses are generated by this server — copy them into WiPay's Developer page."
      />
      <ListState rows={links} error={error} onRetry={load} emptyMessage="No links." />
      {links?.length > 0 && (
        <div className="card overflow-x-auto">
          <table className="w-full text-left text-xs text-slate-700">
            <thead className="table-header-row uppercase">
              <tr>
                <th className="px-5 py-3">Link</th>
                <th className="px-5 py-3">Address</th>
                <th className="px-5 py-3">Status</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100 align-top">
              {links.map((l) => (
                <tr key={l.label}>
                  <td className="px-5 py-3">
                    <p className="font-bold text-slate-900">{l.label}</p>
                    <p className="text-slate-500">
                      {l.kind}
                      {l.setting && <> · set by <code>{l.setting}</code></>}
                      {l.generated && ' · generated by the server'}
                    </p>
                  </td>
                  <td className="px-5 py-3 font-mono break-all">
                    {l.url ?? '—'}
                    {l.generated && l.url && (
                      <button
                        type="button"
                        onClick={() => navigator.clipboard.writeText(l.url).then(() => notify('Copied.'))}
                        className="ml-2 inline-flex items-center gap-1 text-secondary hover:underline font-sans font-bold"
                      >
                        <Copy className="w-3.5 h-3.5" /> Copy
                      </button>
                    )}
                  </td>
                  <td className="px-5 py-3">
                    <Badge className={STATUS[l.status][1]}>{STATUS[l.status][0]}</Badge>
                    {l.problems.map((p) => (
                      <p key={p} className="mt-1 text-slate-600">
                        {p}
                      </p>
                    ))}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      )}
    </div>
  );
}
